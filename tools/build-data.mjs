import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jsonPath = join(root, 'app', 'data', 'trophies.json');
const jsPath = join(root, 'app', 'data', 'trophies.js');

const data = JSON.parse(readFileSync(jsonPath, 'utf8'));
const required = ['trophies', 'sources', 'stages'];
for (const key of required) {
  if (!(key in data)) throw new Error(`trophies.json is missing "${key}"`);
}
if (!Array.isArray(data.trophies) || data.trophies.length !== 55) {
  throw new Error(`expected 55 trophies, found ${Array.isArray(data.trophies) ? data.trophies.length : 'none'}`);
}
if (!Array.isArray(data.stages) || data.stages.length !== 9) {
  throw new Error('expected 9 roadmap lanes (eight stages plus platinum)');
}

const meta = {
  game: data.game,
  platform: data.platform,
  list: data.list,
  checked: data.checked,
};

const banner = '// Generated by tools/build-data.mjs from trophies.json. Do not edit by hand.\n';
const body = [
  banner,
  `export const meta = ${JSON.stringify(meta)};`,
  `export const sources = ${JSON.stringify(data.sources)};`,
  `export const stages = ${JSON.stringify(data.stages)};`,
  `export const trophies = ${JSON.stringify(data.trophies)};`,
  'export default { meta, sources, stages, trophies };',
  '',
].join('\n');

writeFileSync(jsPath, body);
console.log(`build-data: wrote ${data.trophies.length} trophies, ${data.stages.length} lanes, ${Object.keys(data.sources).length} sources`);
